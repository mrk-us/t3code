import * as Hugeicons from "@hugeicons/core-free-icons";
import { HugeiconsIcon, type IconSvgElement } from "@hugeicons/react";
import type { ReactElement, SVGProps } from "react";

export type IconProps = SVGProps<SVGSVGElement> & {
  readonly size?: number | string;
  readonly absoluteStrokeWidth?: boolean;
};
export type IconComponent = (props: IconProps) => ReactElement;

// `data-icon` is the stable hook themes use to restyle every app icon.
function icon(svg: IconSvgElement): IconComponent {
  return ({ strokeWidth, ...props }) => (
    <HugeiconsIcon
      aria-hidden
      data-icon=""
      {...props}
      {...(strokeWidth === undefined ? {} : { strokeWidth: Number(strokeWidth) })}
      icon={svg}
    />
  );
}

